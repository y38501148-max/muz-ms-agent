import type { Difficulty, Question, Topic } from '../shared/types'

export { topicLabels, difficultyLabels, modeLabels } from './profiles'

type CardInput = {
  id: string; title: string; topic: Topic; tags: string[]; roles: string[]
  stems: [string, string, string]
  expected: Record<Difficulty, number[]>
  points: [string, string, string, string]
  followups: [string, number[]][]
  hints: string[]; pitfalls: string[]; answer: string
  sources?: Question['sources']
}

// Every card is an original simulated question. Sources explain concepts, never imply a company asked it.
function card(input: CardInput): Question {
  const levels: Difficulty[] = ['easy', 'medium', 'hard']
  const variants = Object.fromEntries(levels.map((level, index) => [level, {
    stem: input.stems[index], expectedPointIds: input.expected[level].map(n => `p${n}`),
  }])) as Question['variants']
  return {
    id: input.id, familyId: input.id, version: 1, title: input.title, topic: input.topic,
    tags: input.tags, roles: input.roles, origin: 'generated', review: 'assistant_checked', variants,
    points: input.points.map((text, i) => ({ id: `p${i + 1}`, text })),
    followups: input.followups.map(([prompt, targets], i) => ({ id: `f${i + 1}`, prompt, targetPointIds: targets.map(n => `p${n}`) })),
    hints: input.hints, pitfalls: input.pitfalls, referenceAnswer: input.answer, sources: input.sources ?? [],
  }
}
